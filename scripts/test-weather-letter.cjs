const assert = require("node:assert/strict");
const {build, number, probability, defaultPeriod} = require("../src/main/resources/static/weather-letter.js");
assert.equal(number(null), null);
assert.equal(number(""), null);
assert.equal(probability("-"), null);
assert.equal(probability("0"), 0);
const fixture = {morning:{tmp:"0",tmn:"-2",tmx:"7",pop:"0",airQualitySummary:"보통"}};
assert.match(build(fixture, []).range, /최저 -2°C/);
assert.equal(build(fixture, []).rain, "최대 0%");
assert.equal(build({}, []).rain, "강수 자료 없음");
assert.doesNotMatch(build({}, []).headline, /가능성이 낮/);
const wet=build(fixture,[{time:"18:00",precipitation:"비",precipitationProbability:70}]);
assert.equal(wet.headline,"18:00 무렵 비가 올 수 있어요. 외출 전 한 번 더 확인해요");
const partial=build(fixture,[{time:"18:00",precipitationProbability:0},{time:"19:00",precipitationProbability:null}]);
assert.equal(partial.rain,"확인된 시간 최대 0%");
assert.doesNotMatch(partial.headline,/가능성이 낮/);
assert.equal(build({},[{temperature:null,precipitationProbability:null}]).range,"기온 자료 없음");
assert.equal(build({morning:{tmp:null}},[{temperature:12,precipitationProbability:0}]).range,"시간대 12°C ~ 12°C");
assert.equal(build({dayLabel:"내일"},[{precipitationProbability:0}]).headline,"내일 예보에는 비 소식이 적어요. 시간별로 확인해 보세요");
assert.equal(build({dayLabel:"모레"},[{time:"09:00",precipitation:"눈",precipitationProbability:70}]).headline,"모레 09:00 무렵 눈이 올 수 있어요. 외출 전 한 번 더 확인해요");
assert.equal(defaultPeriod(0,new Date("2026-10-23T00:00:00Z")),"MORNING");
assert.equal(defaultPeriod(0,new Date("2026-10-23T03:00:00Z")),"AFTERNOON");
assert.equal(defaultPeriod(0,new Date("2026-10-23T12:00:00Z")),"EVENING");
assert.equal(defaultPeriod(1,new Date("2026-10-23T12:00:00Z")),"MORNING");
assert.doesNotMatch(build({headline:"오늘 아침 외출을 추천해요",morning:{tmp:15,pop:null}},[]).headline,/아침|추천/);
console.log("Weather letter: 20 assertions passed");
